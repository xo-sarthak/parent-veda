//  pop-up picks from the tips for the child's own age, so a mother of a
//  four-month-old never meets a toddler tip.
//
//  ⚠️ IDS ARE KEYS, NOT POSITIONS. `kDailyTips` is saved as 'tip_N' (its
//  index), which is why it cannot be reordered. These are saved as
//  'atip_<key>', so the list can grow and be reordered freely.
//
//  REQUIRED_REVIEW: every tip, by a paediatrician, as the header above says.
// =============================================================================

class AgeTip {
  const AgeTip(this.key, this.fromWeek, this.toWeek, this.tip);

  /// Stable id fragment. Never derived from the title.
  final String key;

  /// Inclusive start, exclusive end, in weeks of age.
  final int fromWeek;
  final int toWeek;
  final DailyTip tip;

  String get id => 'atip_$key';
  bool fits(int weeks) => weeks >= fromWeek && weeks < toWeek;
}

