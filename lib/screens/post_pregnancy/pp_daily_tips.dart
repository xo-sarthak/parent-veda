/// The tips that fit a child of [weeks] old. Past the last window, the last
/// window's tips, so a six-year-old still gets something sensible.
List<AgeTip> ageTipsFor(int weeks) {
  final fit = [for (final t in kAgeTips) if (t.fits(weeks)) t];
  if (fit.isNotEmpty) return fit;
  final last = kAgeTips.last.fromWeek;
  return [for (final t in kAgeTips) if (t.fromWeek == last) t];
}

/// Today's tip for this child, or null when there is no child with a birth
/// date yet (the general rotation is used then).
AgeTip? _ageTipToday([DateTime? on]) {
  final child = ChildProfileStore.instance;
  if (!child.hasRealChild) return null;
  final now = on ?? DateTime.now();
  final doy = now.difference(DateTime(now.year)).inDays;
  final pool = ageTipsFor(child.ageInWeeks.floor());
  return pool[doy % pool.length];
}
