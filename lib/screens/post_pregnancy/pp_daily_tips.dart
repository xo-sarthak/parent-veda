/// Today's tip — stable within a calendar day. For a child with a birth date,
/// a tip for his age (see `kAgeTips`); otherwise the general rotation.
DailyTip dailyTip() {
  final age = _ageTipToday();
  if (age != null) return age.tip;
  final now = DateTime.now();
  final doy = now.difference(DateTime(now.year)).inDays;
  return kDailyTips[doy % kDailyTips.length];
}

/// A stable id for today's tip, so a save survives a restart.
String dailyTipId([DateTime? on]) {
  final age = _ageTipToday(on);
  if (age != null) return age.id;
  final now = on ?? DateTime.now();
  final doy = now.difference(DateTime(now.year)).inDays;
  return 'tip_${doy % kDailyTips.length}';
}

/// The tip behind a saved id ('tip_N'), or null for an id this build does
/// not have. Used for the Saved screen's title snapshot; a null renders as
/// "No longer available", never as a wrong tip.
DailyTip? dailyTipById(String id) {
  if (id.startsWith('atip_')) {
    for (final t in kAgeTips) {
      if (t.id == id) return t.tip;
    }
    return null;
  }
  final n = int.tryParse(id.replaceFirst('tip_', ''));
  if (n == null || n < 0 || n >= kDailyTips.length) return null;
  return kDailyTips[n];
}

String dailyTipTitle(String id) => dailyTipById(id)?.title ?? '';

/// The plain-text form used by the share sheet.
///
/// Includes the source line: a tip forwarded to a WhatsApp group with no
/// provenance is exactly the kind of parenting advice this app exists to be an
/// alternative to.
String dailyTipShareText(DailyTip t) {
  final b = StringBuffer()
    ..writeln(t.title)
    ..writeln()
    ..writeln(t.body);
  if (t.why.isNotEmpty) {
    b
      ..writeln()
      ..writeln('Why it works: ${t.why}');
  }
  if (t.source.isNotEmpty) b.writeln('Based on: ${t.source}');
  b
    ..writeln()
    ..write('via ParentVeda — general guidance, not advice about one child.');
  return b.toString();
}

