/// A meal plan for [days] days (each day = the five slots). Deterministic per
/// day index so "regenerate" can vary it without randomness in tests.
/// Slots a thin pool can honestly borrow from. A baby's lunch and dinner are
/// interchangeable, and the two snack slots are the same kind of food - so a
/// slot with only a couple of recipes tops itself up rather than repeating.
const Map<String, List<String>> _slotNeighbours = {
  'Breakfast': ['Morning snack'],
  'Morning snack': ['Evening snack', 'Breakfast'],
  'Lunch': ['Dinner'],
  'Evening snack': ['Morning snack'],
  'Dinner': ['Lunch'],
};

/// ⚠️ `diet` IS A FILTER THE PLAN ACCEPTS, NOT A NEW PREFERENCE STORE.
///
/// Feedback: "in meal plan section, give filters for veg non veg, egg, vegan,
/// all." The obvious implementation is a second persisted setting beside
/// `FoodStore.vegOnly` — and then two switches can disagree, and the day one
/// says veg while the other says non-veg is a bug nobody can reproduce.
///
/// So this is a per-screen filter passed in, layered ON TOP of the household's
/// `vegOnly` switch rather than replacing it. A vegetarian household that asks
/// for "Non-veg" here still gets nothing, which is correct: the household
/// setting is the harder constraint and a browsing filter must not quietly
/// override it.
///
/// `null` means no narrowing, which is the 'All' chip.
Map<String, FoodRecipe> planForDay(int dayIndex, {String? diet}) {
  final vegOnly = FoodStore.instance.vegOnly;

  bool matchesDiet(FoodRecipe r) => switch (diet) {
        'veg' => r.veg,
        'vegan' => r.vegan,
        'egg' => r.egg,
        // Not `!veg`: that silently included every egg dish.
        'nonveg' => !r.veg && !r.egg,
        _ => true,
      };

  List<FoodRecipe> poolFor(String s) {
    bool ok(FoodRecipe r) =>
        !r.comfortOnly && (!vegOnly || r.veg) && matchesDiet(r);
    final own = foodCatalog.where((r) => r.slot == s && ok(r)).toList();
    // A WEEKLY plan drawn from a pool of two is the same dinner four times, so
    // top up thin slots from their neighbours. Dinner currently has only two
    // recipes authored - this keeps the plan varied until more are written.
    if (own.length >= 4) return own;
    final extra = <FoodRecipe>[];
    for (final n in _slotNeighbours[s] ?? const <String>[]) {
      extra.addAll(foodCatalog.where((r) => r.slot == n && ok(r)));
    }
    final merged = [...own, ...extra];
    if (merged.isNotEmpty) return merged;
    // ⚠️ STILL `ok`, NOT THE WHOLE CATALOGUE. This last resort already
    // respected vegOnly and now respects the diet filter too — dropping the
    // predicate here would put chicken on a screen filtered to Veg, which is
    // the worst possible place for a fallback to be generous.
    return foodCatalog.where(ok).toList();
  }

  // Each slot walks its pool at a DIFFERENT stride, so Tuesday is not simply
  // Monday shifted by one across the board.
  FoodRecipe slot(String s, int stride) {
    final list = poolFor(s);
    if (list.isEmpty) return foodCatalog.first;
    return list[((dayIndex * stride) + stride) % list.length];
  }

  return {
    'Breakfast': slot('Breakfast', 1),
    'Morning snack': slot('Morning snack', 2),
    'Lunch': slot('Lunch', 1),
    'Evening snack': slot('Evening snack', 3),
    'Dinner': slot('Dinner', 2),
  };
}

/// Smart Meal Builder: given a [meal] slot, [maxMinutes] available and the
/// ingredients the parent [has], suggest recipes (best ingredient-overlap first)
/// that fit the time. Returns each suggestion with the ingredients still to buy.
class MealSuggestion {
  const MealSuggestion(this.recipe, this.missing, this.matched);
  final FoodRecipe recipe;
  final List<String> missing; // ingredient keys not in the pantry
  final int matched; // how many pantry items it uses
}

List<MealSuggestion> buildMeals({required String meal, required int maxMinutes, required Set<String> has}) {
  final scored = <MealSuggestion>[];
  for (final r in foodCatalog) {
    if (r.slot != meal) continue;
    if (r.comfortOnly) continue; // sick-day meals never surface in everyday planning
    if (r.totalMin > maxMinutes) continue;
    if (FoodStore.instance.vegOnly && !r.veg) continue;
    final matched = r.ingredientKeys.where(has.contains).length;
    final missing = r.ingredientKeys.where((k) => !has.contains(k)).toList();
    scored.add(MealSuggestion(r, missing, matched));
  }
  scored.sort((a, b) {
    if (b.matched != a.matched) return b.matched.compareTo(a.matched); // most pantry use first
    return a.recipe.totalMin.compareTo(b.recipe.totalMin); // then quickest
  });
  return scored.take(5).toList();
}

// =============================================================================
//  FoodStore - saved recipes + the shopping list (ingredient -> purchased).
// =============================================================================
class FoodStore extends ChangeNotifier with CloudSyncedStore {
  FoodStore._();
  static final FoodStore instance = FoodStore._();

  final Set<String> _saved = {'moongkhichdi', 'ragipancake'};
  final Map<String, bool> _shopping = {}; // ingredient line -> purchased
  final List<String> _cooked = ['moongkhichdi', 'sweetpotatomash'];
  bool _vegOnly = false;

  // ---- persistence (user_state KV; own-only, a personal preference) --------
  static const _prefsKey = 'pp_food';

  @override
  String get cloudKey => _prefsKey;

  @override
  Object cloudData() => {
        'saved': _saved.toList(),
        'shopping': _shopping,
        'cooked': _cooked,
        'vegOnly': _vegOnly,
      };

  @override
  void applyCloudData(Object data) {
    if (data is! Map) return;
    final s = data['saved'];
    if (s is List) _saved..clear()..addAll(s.map((e) => e.toString()));
    final c = data['cooked'];
    if (c is List) _cooked..clear()..addAll(c.map((e) => e.toString()));
    final sh = data['shopping'];
    if (sh is Map) {
      _shopping
        ..clear()
        ..addAll(sh.map((k, v) => MapEntry(k.toString(), v == true)));
    }
    _vegOnly = data['vegOnly'] == true;
  }

  @override
  Future<void> persistLocalCache() async {
    try {
      final prefs = await SharedPreferences.getInstance();
      await prefs.setString(_prefsKey, jsonEncode(cloudData()));
    } catch (_) {}
  }

  // The mixin's override pushes to the cloud; this keeps the LOCAL cache
  // current too, so an offline/logged-out user still gets persistence. Every
  // mutation already calls notifyListeners(), so one override covers them all.
  @override
  void notifyListeners() {
    super.notifyListeners();
    persistLocalCache();
  }

  Future<void> init() async {
    try {
      final prefs = await SharedPreferences.getInstance();
      final raw = prefs.getString(_prefsKey);
      if (raw != null) applyCloudData(jsonDecode(raw));
    } catch (_) {/* keep the starter state */}
    notifyListeners();
    try {
      await syncStateFromCloud();
    } catch (_) {/* stay local */}
  }


  bool isSaved(String id) => _saved.contains(id);
  void toggleSave(String id) {
    _saved.contains(id) ? _saved.remove(id) : _saved.add(id);
    notifyListeners();
  }

  /// Vegetarian-only mode: when on, every suggestion, plan, recommendation and
  /// Smart-Meal-Builder result is filtered to vegetarian recipes.
  bool get vegOnly => _vegOnly;
  void setVeg(bool v) {
    _vegOnly = v;
    notifyListeners();
  }

  void toggleVeg() => setVeg(!_vegOnly);

  List<FoodRecipe> get saved => _saved.map(foodRecipeById).toList();
  List<FoodRecipe> get recentlyCooked => _cooked.map(foodRecipeById).toList();

  Map<String, bool> get shopping => Map.unmodifiable(_shopping);
  int get shoppingCount => _shopping.length;
  int get shoppingLeft => _shopping.values.where((p) => !p).length;

  /// Add a recipe's ingredients to the shopping list (skips ones already there).
  void addRecipeToShopping(FoodRecipe r) {
    for (final ing in r.ingredients) {
      _shopping.putIfAbsent(ing, () => false);
    }
    notifyListeners();
  }

  /// Add specific ingredient lines (used by the Smart Meal Builder's "buy missing").
  void addLines(Iterable<String> lines) {
    for (final l in lines) {
      _shopping.putIfAbsent(l, () => false);
    }
    notifyListeners();
  }

  void togglePurchased(String line) {
    _shopping[line] = !(_shopping[line] ?? false);
    notifyListeners();
  }

  void clearPurchased() {
    _shopping.removeWhere((_, purchased) => purchased);
    notifyListeners();
  }

  /// ⚠️ REMOVING ONE LINE WAS SIMPLY MISSING, AND THAT IS THE WHOLE BUG.
  ///
  /// Reported as "once the shopping list is cleared by user, it is not getting
  /// removed ... this is happening after clicking add ingredients to shopping
  /// list". Nothing was broken: `clearPurchased` works, the store persists,
  /// and the screen rebuilds. The list simply had NO DELETE. Adding a recipe
  /// put twelve lines in, and the only way to get one out was to tick it
  /// bought — lying to the app about having bought coriander — and then find
  /// the clear link, which itself only appears once something is ticked.
  ///
  /// The general shape is worth keeping: a feature can be complete in every
  /// direction it was designed for and still be a trap, because ADD was
  /// specified and REMOVE was never named. Nothing fails; the data just
  /// accumulates.
  void removeLine(String line) {
    if (_shopping.remove(line) != null) notifyListeners();
  }

  /// Empty the list, bought or not. Separate from [clearPurchased] on purpose:
  /// one is "tidy up what I have done", the other is "start again".
  void clearShopping() {
    if (_shopping.isEmpty) return;
    _shopping.clear();
    notifyListeners();
  }
}
