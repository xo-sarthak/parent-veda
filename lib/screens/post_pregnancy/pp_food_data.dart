/// One key nutrient line for the Nutrition Breakdown.
class FoodNutrient {
  const FoodNutrient(this.name, this.amount, this.note);
  final String name; // 'Iron'
  final String amount; // 'good source'
  final String note; // one-line why
}

/// A food/recipe - the unit of the Food companion.
class FoodRecipe {
  const FoodRecipe({
    required this.id,
    required this.title,
    required this.subtitle,
    required this.category,
    required this.slot,
    required this.ageTag,
    required this.veg,
    required this.prepMin,
    required this.cookMin,
    required this.difficulty,
    required this.seed,
    required this.highlight,
    required this.why,
    required this.nutrients,
    required this.frequency,
    required this.ingredients,
    required this.steps,
    // What you need in the kitchen beyond a spoon and a plate. Called out
    // separately because discovering you need a blender halfway through is the
    // difference between cooking this and abandoning it.
    this.equipment = const [],
    required this.storage,
    required this.mistakes,
    required this.substitutions,
    required this.healthierNote,
    required this.tags,
    required this.ingredientKeys,
    this.vegan = false, // veg AND vegan (no dairy/egg)
    this.egg = false, // eggetarian: not veg, and not non-veg either
    this.immunity = false, // immunity-booster tag/filter
    this.serves = 2,
    this.situations = const {}, // sick-day situations this dish helps with
    this.comfortOnly = false, // a pure comfort/recovery meal (hidden from everyday browse)
    this.relatedArticle,
    this.relatedVideoId,
    this.relatedProductId,
    this.relatedCommunity,
  });

  final String id;
  final String title;
  final String subtitle;
  final String category;
  final String slot; // meal slot: Breakfast / Morning snack / Lunch / …
  final String ageTag; // '6 to 12 mo'
  final bool veg;
  final int prepMin;
  final int cookMin;
  final String difficulty;
  final int seed;
  final String highlight; // 'Iron + calcium'
  final String why; // why this is good (educational)
  final List<FoodNutrient> nutrients;
  final String frequency; // 'A few times a week'
  final List<String> ingredients;
  final List<String> equipment;
  final List<String> steps;
  final List<String> storage;
  final List<String> mistakes;
  final Map<String, String> substitutions; // item -> swap
  final String healthierNote; // what changed & why it's healthier
  final Set<String> tags; // search / nutrition tags
  final Set<String> ingredientKeys; // canonical keys for the Smart Meal Builder
  final bool vegan;

  /// ⚠️ EGGETARIAN IS ITS OWN CATEGORY IN INDIA, AND LEAVING IT OUT WAS A
  /// REAL MISFILING RATHER THAN A MISSING FILTER.
  ///
  /// The model had `veg` and `vegan` only, so `diet` had three outcomes and an
  /// egg dish had to be one of them. Egg bhurji was `veg: false`, which put it
  /// under "Non-veg" — next to chicken and fish. A vegetarian household that
  /// eats eggs (a very large share of Indian families, and the reason
  /// "eggetarian" is a word here at all) would filter to Veg and never see the
  /// one high-protein weaning breakfast in the library.
  ///
  /// So this is not "add a chip". A wrong bucket hides food from the people it
  /// was written for, and the filter was merely the symptom.
  final bool egg;

  final bool immunity;
  final int serves;
  final Set<String> situations; // sick-day situations (Constipation / Fever / …)
  final bool comfortOnly;
  final String? relatedArticle;
  final String? relatedVideoId;
  final String? relatedProductId;
  final String? relatedCommunity;

  int get totalMin => prepMin + cookMin;

  /// ⚠️ ORDER MATTERS AND IT IS NOT ALPHABETICAL. Vegan is checked first
  /// because a vegan dish is also vegetarian, and egg before the veg/non-veg
  /// split because an egg dish is neither in the sense the filter means.
  String get vegLabel => vegan
      ? 'Vegan'
      : egg
          ? 'Egg'
          : veg
              ? 'Veg'
              : 'Non-veg';

  /// 'veg' | 'vegan' | 'egg' | 'nonveg' - drives the diet filter and the marker.
  String get diet => vegan
      ? 'vegan'
      : egg
          ? 'egg'
          : veg
              ? 'veg'
              : 'nonveg';
}

