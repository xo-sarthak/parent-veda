/// The page title behind a `pp_page/<section>/<page>` link, or null when the
/// page is gone (then the tip simply shows no link).
String? ppPageTitleForSurface(String surface) {
  final parts = surface.split('/');
  if (parts.length != 3 || parts[0] != 'pp_page') return null;
  return ppSectionFor(parts[1])?.pageById(parts[2])?.title;
}
